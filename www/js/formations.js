const XI_LAT = [0, -1, -0.3, 0.3, 1, -0.5, 0, 0.5, -1, 0, 1]; // yedek verideki 4-3-3 sırası
export function lateral(p) {
  const a = (p?.pa || '').toUpperCase();
  if (/(^L|-L$)/.test(a)) return -1; if (/(^R|-R$)/.test(a)) return 1;
  if (p?.xi != null) return XI_LAT[p.xi] ?? 0;
  return 0;
}
