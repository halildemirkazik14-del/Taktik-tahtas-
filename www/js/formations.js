// ESPN'den "4-2-3-1" gibi listede olmayan bir diziliş gelirse genel yerleşim üret
export function formSlots(name) {
  if (FORMS[name]) return FORMS[name];
  const lines = String(name || '').split(/[-–]/).map((x) => parseInt(x, 10)).filter((n) => n > 0);
  if (lines.reduce((a, b) => a + b, 0) !== 10) return FORMS['4-3-3'];
  const out = [[.5, 0]];
  lines.forEach((n, li) => {
    const depth = 0.22 + (li / Math.max(1, lines.length - 1)) * 0.72;
    const w = n === 1 ? 0 : n === 2 ? 0.3 : n === 3 ? 0.52 : n === 4 ? 0.8 : 0.88;
    for (let i = 0; i < n; i++) {
      const x = n === 1 ? .5 : .5 - w / 2 + (w * i) / (n - 1);
      const wingDrop = (n >= 4 && (i === 0 || i === n - 1)) ? 0.06 : 0;
      out.push([x, depth + (li === 0 ? wingDrop : 0)]);
    }
  });
  return out;
}

// Yuvanın kabaca rolü (dizilişte en yakın oyuncuyu seçerken kullanılır)
export function slotGroup(name, i) {
  if (i === 0) return 'G';
  const [x, d] = formSlots(name)[i];
  if (d < 0.36) return 'D';
  if (d >= 0.85) return 'F';
  if (d >= 0.65 && (x < 0.25 || x > 0.75)) return 'F'; // kanat forvetleri
  return 'M';
}
